/// <summary>
/// 界面文案的集中定义。
///
/// <para><b>为什么不用 AssetRipper 的 Localization。</b>那套是源生成器从
/// <c>Localizations/*.json</c> 生成的、面向服务端 HTML 的静态属性，拿不到
/// 「某个枚举值对应哪段说明」的结构化数据，也没法把文案随 API 一起发给前端。
/// 这里用一张显式的双语表，前端拿到 <see cref="Text"/> 就能直接渲染。</para>
/// </summary>
internal static class LocalizedText
{
	public static string CurrentLanguage { get; private set; } = "zh-Hans";

	public static void SetLanguage(string? code)
	{
		CurrentLanguage = Normalize(code);
	}

	public static string Normalize(string? code) => code?.ToLowerInvariant() switch
	{
		"en" or "en-us" or "en_us" => "en",
		_ => "zh-Hans",
	};

	/// <summary>取文案。<paramref name="key"/> 缺英文时回退中文，不会露出 key。</summary>
	public static string Get(string key)
	{
		Dictionary<string, string> table = CurrentLanguage == "en" ? En : Zh;
		if (table.TryGetValue(key, out string? value))
		{
			return value;
		}
		return Zh.TryGetValue(key, out string? fallback) ? fallback : key;
	}

	/// <summary>语言选项，供前端渲染切换器。</summary>
	public static IReadOnlyList<(string Code, string Name)> Languages { get; } =
	[
		("zh-Hans", "简体中文"),
		("en", "English"),
	];

		/// <summary>当前语言的完整文案表，随 /api/text 一次性发给前端。</summary>
		public static Dictionary<string, string> Export() => new(CurrentLanguage == "en" ? En : Zh, StringComparer.Ordinal);

