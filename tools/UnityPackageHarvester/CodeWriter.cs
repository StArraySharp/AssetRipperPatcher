using System.Text;

namespace AssetRipperPatcher.Tools.UnityPackages;

/// <summary>
/// 把提取到的数据写成主工程能编译的 C# 数据文件。
///
/// <para><b>为什么只写数据。</b>主工程里的 <c>UnityPackageCatalog</c> 负责全部查询逻辑，
/// 这里只产出 <c>Packages</c> 这个 <c>List&lt;UnityPackage&gt;</c>。手写与生成分离，
/// 重跑工具不会覆盖手写代码。</para>
/// </summary>
internal static class CodeWriter
{
    /// <summary>写 <c>UnityPackageCatalog.Generated.cs</c>：<c>List&lt;UnityPackage&gt;</c>。</summary>
    public static void WriteCatalog(string path, IEnumerable<PackageModel> packages)
    {
        List<PackageModel> ordered = packages
            .Where(static p => p.Name.Length > 0)
            .OrderBy(static p => p.Name, StringComparer.Ordinal)
            .ToList();

        int assemblyCount = ordered.Sum(static p => p.AsmDefs.Count);
        int typeCount = ordered.Sum(static p => p.AsmDefs.Sum(static a => a.Types.Count));

        StringBuilder sb = new();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//     Generated by tools/UnityPackageHarvester from https://packages.unity.com");
        sb.AppendLine($"//     {ordered.Count} package(s), {assemblyCount} asmdef(s), {typeCount} serializable type(s).");
        sb.AppendLine("//     Do not edit by hand: rerun the generator instead.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("using AssetRipper.Primitives;");
        sb.AppendLine();
        sb.AppendLine("namespace AssetRipperPatcher;");
        sb.AppendLine();
        sb.AppendLine("public static partial class UnityPackageCatalog");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>全部已知的 Unity 官方包。</summary>");
        sb.AppendLine("    private static readonly UnityPackage[] Packages =");
        sb.AppendLine("    [");

        foreach (PackageModel package in ordered)
        {
            WritePackage(sb, package);
        }

        sb.AppendLine("    ];");
        sb.AppendLine("}");

        WriteFile(path, sb);
    }

    private static void WritePackage(StringBuilder sb, PackageModel package)
    {
        sb.AppendLine("        new UnityPackage");
        sb.AppendLine("        {");
        sb.AppendLine($"            name = \"{Escape(package.Name)}\",");
        if (package.DisplayName.Length > 0)
        {
            sb.AppendLine($"            displayName = \"{Escape(package.DisplayName)}\",");
        }
        sb.AppendLine($"            version = \"{Escape(package.Version)}\",");
        if (package.Unity.Length > 0)
        {
            sb.AppendLine($"            unity = \"{Escape(package.Unity)}\",");
        }
        if (package.Category.Length > 0)
        {
            sb.AppendLine($"            category = \"{Escape(package.Category)}\",");
        }
        if (package.Description.Length > 0)
        {
            sb.AppendLine($"            description = \"{Escape(Flatten(package.Description))}\",");
        }

        if (package.Dependencies.Count > 0)
        {
            sb.AppendLine("            dependencies = new()");
            sb.AppendLine("            {");
            foreach ((string name, string version) in package.Dependencies
                .OrderBy(static d => d.Key, StringComparer.Ordinal))
            {
                sb.AppendLine($"                [\"{Escape(name)}\"] = \"{Escape(version)}\",");
            }
            sb.AppendLine("            },");
        }

        string[] guids = package.AllGuids.ToArray();
        if (guids.Length > 0)
        {
            sb.AppendLine("            guids =");
            sb.AppendLine("            [");
            foreach (string guid in guids)
            {
                sb.AppendLine($"                UnityGuid.Parse(\"{guid}\"),");
            }
            sb.AppendLine("            ],");
        }

        // 空 asmdef 列表写成 `[]`：绝大多数包没有程序集（只有资源），
        // 省略会让对象初始化器里少一个字段，但显式写出来读代码时更直观。
        if (package.AsmDefs.Count == 0)
        {
            sb.AppendLine("            asmdefs = [],");
        }
        else
        {
            sb.AppendLine("            asmdefs =");
            sb.AppendLine("            [");
            foreach (AsmDefModel asmdef in package.AsmDefs
                .OrderBy(static a => a.Name, StringComparer.Ordinal))
            {
                WriteAsmDef(sb, asmdef);
            }
            sb.AppendLine("            ],");
        }

        sb.AppendLine("        },");
    }

    private static void WriteAsmDef(StringBuilder sb, AsmDefModel asmdef)
    {
        sb.AppendLine("                new AsmDef");
        sb.AppendLine("                {");
        sb.AppendLine($"                    name = \"{Escape(asmdef.Name)}\",");
        if (asmdef.Guid.Length > 0)
        {
            sb.AppendLine($"                    guid = \"{asmdef.Guid}\",");
        }

        if (asmdef.Types.Count == 0)
        {
            sb.AppendLine("                    types = [],");
        }
        else
        {
            sb.AppendLine("                    types =");
            sb.AppendLine("                    [");
            foreach (TypeModel type in asmdef.Types
                .OrderBy(static t => t.Namespace, StringComparer.Ordinal)
                .ThenBy(static t => t.Name, StringComparer.Ordinal))
            {
                string guid = type.Guid.Length > 0 ? type.Guid : UnityGuidOf(type);
                sb.AppendLine($"                        new ScriptType {{ @namespace = \"{Escape(type.Namespace)}\", " +
                    $"name = \"{Escape(type.Name)}\", guid = UnityGuid.Parse(\"{guid}\") }},");
            }
            sb.AppendLine("                    ],");
        }

        sb.AppendLine("                },");
    }

    /// <summary>兜底：<c>.cs.meta</c> 缺失时按类型名生成确定性 GUID（只在包本身缺 meta 时走到）。</summary>
    private static string UnityGuidOf(TypeModel type)
    {
        byte[] hash = System.Security.Cryptography.MD5.HashData(
            Encoding.UTF8.GetBytes($"{type.Namespace}.{type.Name}"));
        return Convert.ToHexString(hash).ToLowerInvariant();
    }

    /// <summary>把多行描述压成一行：生成的 C# 用普通字符串字面量，换行会破坏可读性。</summary>
    private static string Flatten(string value) =>
        value.Replace("\r\n", "\n", StringComparison.Ordinal)
                .Replace('\r', '\n')
                .Replace("\\n", " ", StringComparison.Ordinal)
                .Replace('\n', ' ')
                .Trim();

    private static void WriteFile(string path, StringBuilder content)
    {
        string? directory = Path.GetDirectoryName(Path.GetFullPath(path));
        if (directory is not null)
        {
            Directory.CreateDirectory(directory);
        }
        File.WriteAllText(path, content.ToString(), new UTF8Encoding(false));
    }

    private static string Escape(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
                .Replace("\"", "\\\"", StringComparison.Ordinal)
                .Replace("\r", string.Empty, StringComparison.Ordinal)
                .Replace("\n", " ", StringComparison.Ordinal);
}
